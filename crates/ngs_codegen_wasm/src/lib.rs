fn sanitize_name(name: &str) -> String {
    let ok = name.chars().all(|c| c.is_ascii_alphanumeric() || c == '_');
    if ok {
        format!("{name}")
    } else {
        format!("f{}", crc(name))
    }
}

fn sanitize_import_sym(import_name: &str) -> String {
    // import はその名前で宣言されているため同一のサニタイズを適用する
    sanitize_name(import_name)
}

fn crc(s: &str) -> u64 {
    let mut h = 5381u64;
    for b in s.bytes() {
        h = h.wrapping_mul(33).wrapping_add(b as u64);
    }
    h & 0xFFFFF
}

