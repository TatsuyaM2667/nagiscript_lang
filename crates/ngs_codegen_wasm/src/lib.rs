/// 論理型 → wasm 値型。Str/Ptr/集約はアドレス (i32)。
pub fn wty(t: &IrType) -> &'static str {
    match t {
        IrType::Void => "",
        IrType::F32 => "f32",
        IrType::F64 => "f64",
        IrType::I64 | IrType::U64 | IrType::Usize | IrType::Isize => "i64",
        _ => "i32",
    }
}

pub fn is_signed(t: &IrType) -> bool {
    matches!(t, IrType::I8 | IrType::I16 | IrType::I32 | IrType::I64 | IrType::Isize)
}

fn align16(n: u64) -> u64 {
    n.div_ceil(16) * 16
}

