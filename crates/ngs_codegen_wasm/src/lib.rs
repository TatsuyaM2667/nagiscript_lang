enum Callee {
    /// prog.funcs のインデックス
    Local(usize),
    Import(ImportSig),
}

struct FnGen<'a> {
    prog: &'a IrProgram,
    seg: &'a DataSeg,
    f: &'a ngs_ir::IrFunction,
    out: String,
    ind: usize,
    /// V id -> 論理型（pass1 推論結果）
    tys: HashMap<V, IrType>,
    /// V id -> ローカル番号
    local_of: HashMap<V, usize>,
    n_locals: usize,
    sret_local: Option<usize>,
    frame_local: usize,
    pc_local: usize,
    scratch: usize,
    /// CheckedBin(Mul) の 64bit 中間値用スクラッチ
    wide_local: usize,
}

/// pass1: 各 V の論理型を推定（LLVM 版の bind 規則と同一）
fn infer_tys(prog: &IrProgram, f: &ngs_ir::IrFunction) -> HashMap<V, IrType> {
    let mut tys = HashMap::new();
    for (i, (_, t)) in f.params.iter().enumerate() {
        tys.insert(i, t.clone());
    }
    for b in &f.blocks {
        for inst in &b.insts {
            match inst {
                Inst::Const { dst, val } => {
                    let t = match val {
                        Const::Int(_) => IrType::I64,
                        Const::Float(_) => IrType::F64,
                        Const::Bool(_) => IrType::Bool,
                        Const::Str(_) => IrType::Str,
                        Const::NullPtr => IrType::Ptr(std::rc::Rc::new(IrType::U8)),
                    };
                    tys.insert(*dst, t);
                }
                Inst::Alloca { dst, .. } => {
                    // alloca の結果は「セルのアドレス」（wasm では i32）
                    tys.insert(*dst, IrType::Ptr(std::rc::Rc::new(IrType::U8)));
                }
                Inst::Load { dst, ty, .. } => {
                    tys.insert(*dst, ty.clone());
                }
                Inst::BinOp { dst, ty, .. } => {
                    tys.insert(*dst, ty.clone());
                }
                Inst::CmpOp { dst, .. } => {
                    tys.insert(*dst, IrType::Bool);
                }
                Inst::CheckedBin { dst_val, dst_ovf, ty, .. } => {
                    tys.insert(*dst_val, ty.clone());
                    tys.insert(*dst_ovf, IrType::Bool);
                }
                Inst::Call { dst: Some(dst), ret, .. } => {
                    tys.insert(*dst, ret.clone());
                }
                Inst::FieldAddr { dst, .. }
                | Inst::ElemAddr { dst, .. }
                | Inst::AddrOff { dst, .. } => {
                    tys.insert(*dst, IrType::Ptr(std::rc::Rc::new(IrType::U8)));
                }
                Inst::Cast { dst, to, .. } | Inst::Bitcast { dst, to, .. } => {
                    tys.insert(*dst, to.clone());
                }
                Inst::BoxVal { dst, .. } => {
                    tys.insert(*dst, IrType::I64);
                }
                Inst::Store { .. }
                | Inst::CopyAgg { .. }
                | Inst::RcInc { .. }
                | Inst::RcDec { .. }
                | Inst::Call { dst: None, .. } => {}
            }
        }
    }
    let _ = prog;
    tys
}

impl<'a> FnGen<'a> {
    fn w(&mut self, s: &str) {
        writeln!(self.out, "{}{s}", "  ".repeat(self.ind)).ok();
    }

    fn ty_of(&self, v: V) -> IrType {
        self.tys.get(&v).cloned().unwrap_or(IrType::I64)
    }

    /// V の値をスタックへ積む（変換なし・生のまま）
    fn push_val(&mut self, v: V) {
        let l = self.local_of[&v];
        self.w(&format!("local.get {l}"));
    }

    /// スタックトップの生値を from 論理型から to 論理型の表現へ変換する
    fn conv(&mut self, from: &IrType, to: &IrType, signed_hint: Option<bool>) {
        let wf = wty(from);
        let wt = wty(to);
        if wf == wt {
            return;
        }
        let sg = signed_hint.unwrap_or_else(|| is_signed(from));
        match (wf, wt) {
            ("i32", "i64") => {
                if sg {
                    self.w("i64.extend_i32_s");
                } else {
                    self.w("i64.extend_i32_u");
                }
            }
            ("i64", "i32") => self.w("i32.wrap_i64"),
            ("i32", "f32") => {
                if sg {
                    self.w("f32.convert_i32_s");
                } else {
                    self.w("f32.convert_i32_u");
                }
            }
            ("i32", "f64") => {
                if sg {
                    self.w("f64.convert_i32_s");
                } else {
                    self.w("f64.convert_i32_u");
                }
            }
            ("i64", "f32") => {
                if sg {
                    self.w("f32.convert_i64_s");
                } else {
                    self.w("f32.convert_i64_u");
                }
            }
            ("i64", "f64") => {
                if sg {
                    self.w("f64.convert_i64_s");
                } else {
                    self.w("f64.convert_i64_u");
                }
            }
            ("f32", "i32") => {
                if sg {
                    self.w("i32.trunc_f32_s");
                } else {
                    self.w("i32.trunc_f32_u");
                }
            }
            ("f64", "i32") => {
                if sg {
                    self.w("i32.trunc_f64_s");
                } else {
                    self.w("i32.trunc_f64_u");
                }
            }
            ("f32", "i64") => {
                if sg {
                    self.w("i64.trunc_f32_s");
                } else {
                    self.w("i64.trunc_f32_u");
                }
            }
            ("f64", "i64") => {
                if sg {
                    self.w("i64.trunc_f64_s");
                } else {
                    self.w("i64.trunc_f64_u");
                }
            }
            ("f32", "f64") => self.w("f64.promote_f32"),
            ("f64", "f32") => self.w("f32.demote_f64"),
            _ => {
                // 同一スロット幅（ptr↔整数など）は何もしない
            }
        }
    }

    /// 値 v を want（wasm 型）の表現へ強制する
    fn coerce_arg(&mut self, v: V, want: &str) {
        let lt = self.ty_of(v);
        let cur = wty(&lt);
        if cur == want {
            self.push_val(v);
            return;
        }
        self.push_val(v);
        let dummy = match want {
            "i64" => IrType::I64,
            "f32" => IrType::F32,
            "f64" => IrType::F64,
            _ => IrType::I32,
        };
        self.conv(&lt, &dummy, None);
    }

    /// バンプアロケーション（align16）。確保したアドレスをスタックに積む。
    fn emit_bump(&mut self, size: u64) {
        let sz = align16(size.max(1));
        self.w("global.get $heap");
        self.w("global.get $heap");
        self.w(&format!("i32.const {sz}"));
        self.w("i32.add");
        self.w("global.set $heap");
        // スタックには旧 $heap（= 確保アドレス）が残る
    }

    fn restore_heap(&mut self) {
        self.w(&format!("local.get {}", self.frame_local));
        self.w("global.set $heap");
    }

    fn gen_function(&mut self) -> Result<(), CodegenError> {
        let f = self.f;
        // フレーム保存（バンプポインタ復元用）
        self.w("global.get $heap");
        self.w(&format!("local.set {}", self.frame_local));

        // ガードチェーン
        let nb = f.blocks.len();
        self.w("loop $top");
        self.ind += 1;
        self.w("block $next");
        self.ind += 1;
        for (bi, block) in f.blocks.iter().enumerate() {
            if bi == 0 {
                self.w(&format!("local.get {}", self.pc_local));
                self.w("i32.eqz");
            } else {
                self.w(&format!("local.get {}", self.pc_local));
                self.w(&format!("i32.const {bi}"));
                self.w("i32.eq");
            }
            self.w("if");
            self.ind += 1;
            self.w(&format!(";; block {} (pc={bi})", block.label));
            for inst in &block.insts {
                self.gen_inst(inst)?;
            }
            self.gen_term(&block.term)?;
            self.ind -= 1;
            self.w("end");
        }
        self.w(";; 不正な pc は到達不能");
        self.w("unreachable");
        self.ind -= 1;
        self.w("end ;; $next");
        self.w("br 0 ;; $top");
        self.ind -= 1;
        self.w("end ;; $top");
        self.w("unreachable ;; ループは必ず return で抜ける");
        self.w(") ;; func");
        Ok(())
    }

    fn gen_term(&mut self, term: &Term) -> Result<(), CodegenError> {
        match term {
            Term::Ret(None) => {
                self.restore_heap();
                self.w("return");
            }
            Term::Ret(Some(v)) => {
                let vt = self.ty_of(*v);
                if self.f.ret.is_aggregate() {
                    // sret バッファへ実体を転送してから返る
                    let sl = self.sret_local.expect("sret param");
                    let sz = self.prog.size_of(&self.f.ret);
                    self.w(&format!("local.get {sl}"));
                    self.push_val(*v);
                    self.w(&format!("i32.const {sz}"));
                    self.w("memory.copy");
                } else {
                    self.push_val(*v);
                    self.conv(&vt, &self.f.ret, None);
                }
                self.restore_heap();
                self.w("return");
            }
            Term::Br(l) => {
                let idx = self.f.find_block(l).ok_or_else(|| CodegenError(format!("unknown block `{l}`")))?;
                self.w(&format!("i32.const {idx}"));
                self.w(&format!("local.set {}", self.pc_local));
                self.w("br 1 ;; $next");
            }
            Term::CondBr(c, t_label, f_label) => {
                let ti =
                    self.f.find_block(t_label).ok_or_else(|| CodegenError(format!("unknown block `{t_label}`")))?;
                let fi =
                    self.f.find_block(f_label).ok_or_else(|| CodegenError(format!("unknown block `{f_label}`")))?;
                self.push_val(*c);
                self.w("if");
                self.w(&format!("  i32.const {ti}"));
                self.w(&format!("  local.set {}", self.pc_local));
                self.w("else");
                self.w(&format!("  i32.const {fi}"));
                self.w(&format!("  local.set {}", self.pc_local));
                self.w("end");
                self.w("br 1 ;; $next");
            }
            Term::Unreachable => {
                self.w("unreachable");
            }
        }
        Ok(())
    }

    // --- 命令 ---

    fn load_op(t: &IrType) -> &'static str {
        match t {
            IrType::Bool | IrType::I8 | IrType::U8 => "i32.load8_u",
            IrType::I16 | IrType::U16 => "i32.load16_u",
            IrType::F32 => "f32.load",
            IrType::F64 => "f64.load",
            IrType::I64 | IrType::U64 | IrType::Usize | IrType::Isize => "i64.load",
            _ => "i32.load", // i32/u32/ptr/str/集約セル
        }
    }

    fn store_op(t: &IrType) -> &'static str {
        match t {
            IrType::Bool | IrType::I8 | IrType::U8 => "i32.store8",
            IrType::I16 | IrType::U16 => "i32.store16",
            IrType::F32 => "f32.store",
            IrType::F64 => "f64.store",
            IrType::I64 | IrType::U64 | IrType::Usize | IrType::Isize => "i64.store",
            _ => "i32.store",
        }
    }

    fn resolve_callee(&self, name: &str) -> Result<Callee, CodegenError> {
        if let Some(idx) = self.prog.funcs.iter().position(|f| f.name == name && !f.blocks.is_empty()) {
            return Ok(Callee::Local(idx));
        }
        match resolve_import(name) {
            Some(sig) => Ok(Callee::Import(sig)),
            None => Err(CodegenError(format!(
                "`{name}` cannot be called from wasm output (List/Rc intrinsics are not supported by the wasm backend yet)"
            ))),
        }
    }

    fn callee_param_tys(prog: &IrProgram, idx: usize) -> Vec<IrType> {
        prog.funcs[idx].params.iter().map(|(_, t)| t.clone()).collect()
    }

    fn gen_inst(&mut self, inst: &Inst) -> Result<(), CodegenError> {
        match inst {
            Inst::Const { dst, val } => {
                match val {
                    Const::Int(n) => self.w(&format!("i64.const {n}")),
                    Const::Float(x) => {
                        self.w(&format!("i64.const {}", x.to_bits()));
                        self.w("f64.reinterpret_i64");
                    }
                    Const::Bool(b) => self.w(&format!("i32.const {}", if *b { 1 } else { 0 })),
                    Const::Str(id) => {
                        let off = *self.seg.cells.get(*id as usize).ok_or_else(|| {
                            CodegenError(format!("string literal id {id} not found"))
                        })?;
                        self.w(&format!("i32.const {off}"));
                    }
                    Const::NullPtr => self.w("i32.const 0"),
                }
                self.set_local(*dst);
            }
            Inst::Alloca { dst, ty } => {
                let sz = self.prog.size_of(ty);
                self.emit_bump(sz);
                self.set_local(*dst);
            }
            Inst::Load { dst, addr, ty } => {
                self.push_val(*addr);
                self.w(Self::load_op(ty));
                self.set_local(*dst);
            }
            Inst::Store { addr, val, ty } => {
                self.push_val(*addr);
                let lt = self.ty_of(*val);
                self.push_val(*val);
                self.conv(&lt, ty, None);
                self.w(Self::store_op(ty));
            }
            Inst::BinOp { dst, op, ty, a, b } => {
                let at = self.ty_of(*a);
                let bt = self.ty_of(*b);
                self.push_val(*a);
                self.conv(&at, ty, None);
                self.push_val(*b);
                self.conv(&bt, ty, None);
                if ty.is_float() {
                    let mop = match op {
                        IrBin::Add => "add",
                        IrBin::Sub => "sub",
                        IrBin::Mul => "mul",
                        IrBin::Div => "div",
                        IrBin::Mod => {
                            // wasm に剰余命令はないためホストの fmod を利用
                            let pre = matches!(wty(ty), "f32");
                            if pre {
                                self.conv(ty, &IrType::F64, None);
                                self.conv(ty, &IrType::F64, None);
                            }
                            self.w("call $__ngs_fmod");
                            if pre {
                                self.conv(&IrType::F64, ty, None);
                            }
                            self.set_local(*dst);
                            return Ok(());
                        }
                    };
                    let p = wty(ty);
                    self.w(&format!("{p}.{mop}"));
                } else {
                    let s = if is_signed(ty) { "s" } else { "u" };
                    let p = wty(ty);
                    let mop: String = match op {
                        IrBin::Add => "add".into(),
                        IrBin::Sub => "sub".into(),
                        IrBin::Mul => "mul".into(),
                        IrBin::Div => format!("div_{s}"),
                        IrBin::Mod => format!("rem_{s}"),
                    };
                    self.w(&format!("{p}.{mop}"));
                }
                self.set_local(*dst);
            }
            Inst::CmpOp { dst, pred, ty, a, b } => {
                let at = self.ty_of(*a);
                let bt = self.ty_of(*b);
                self.push_val(*a);
                self.conv(&at, ty, None);
                self.push_val(*b);
                self.conv(&bt, ty, None);
                let p = wty(ty);
                let sop = match pred {
                    IrPred::Eq => "eq",
                    IrPred::Ne => "ne",
                    IrPred::Lt => "lt",
                    IrPred::Le => "le",
                    IrPred::Gt => "gt",
                    IrPred::Ge => "ge",
                };
                let op = if ty.is_float() {
                    format!("{p}.{sop}")
                } else {
                    match pred {
                        IrPred::Eq | IrPred::Ne => format!("{p}.{sop}"),
                        _ => {
                            let s = if is_signed(ty) { "s" } else { "u" };
                            format!("{p}.{sop}_{s}")
                        }
                    }
                };
                self.w(&op);
                self.set_local(*dst);
            }
            Inst::CheckedBin { dst_val, dst_ovf, op, ty, a, b } => {
                self.gen_checked_bin(*dst_val, *dst_ovf, *op, ty, *a, *b)?;
            }
            Inst::Call { dst, func, args, ret } => {
                self.gen_call(dst.as_ref().filter(|d| **d != ngs_ir::NO_V), func, args, ret)?;
            }
            Inst::FieldAddr { dst, base, struct_id, field } => {
                let off = self.prog.field_offset(*struct_id, *field);
                self.push_val(*base);
                self.w(&format!("i32.const {off}"));
                self.w("i32.add");
                self.set_local(*dst);
            }
            Inst::ElemAddr { dst, base, index, elem } => {
                let stride = self.prog.cell_of(elem);
                let it = self.ty_of(*index);
                self.push_val(*base);
                self.push_val(*index);
                self.conv(&it, &IrType::I32, None);
                self.w(&format!("i32.const {stride}"));
                self.w("i32.mul");
                self.w("i32.add");
                self.set_local(*dst);
            }
            Inst::AddrOff { dst, base, off } => {
                self.push_val(*base);
                self.w(&format!("i32.const {off}"));
                self.w("i32.add");
                self.set_local(*dst);
            }
            Inst::Cast { dst, kind, val, to } => {
                let from = self.ty_of(*val);
                self.push_val(*val);
                self.gen_cast(*kind, &from, to)?;
                self.set_local(*dst);
            }
            Inst::Bitcast { dst, val, to } => {
                let from = self.ty_of(*val);
                self.push_val(*val);
                self.conv(&from, to, None);
                self.set_local(*dst);
            }
            Inst::CopyAgg { dst_addr, src_ptr, ty } => {
                let sz = self.prog.size_of(ty);
                self.push_val(*dst_addr);
                self.push_val(*src_ptr);
                self.w(&format!("i32.const {sz}"));
                self.w("memory.copy");
            }
            Inst::RcInc { .. } | Inst::RcDec { .. } => {
                return Err(CodegenError(
                    "List/Rc are not supported by the wasm backend yet".into(),
                ));
            }
            Inst::BoxVal { dst, src, ty } => {
                let st = self.ty_of(*src);
                let (imp, argt) = match ty {
                    IrType::Bool => ("__ngs_box_bool", IrType::Bool),
                    IrType::F32 | IrType::F64 => ("__ngs_box_f64", IrType::F64),
                    IrType::Str => ("__ngs_box_str", IrType::Str),
                    t if t.is_int() => ("__ngs_box_i64", IrType::I64),
                    _ => ("__ngs_box_ptr", IrType::Ptr(std::rc::Rc::new(IrType::U8))),
                };
                self.push_val(*src);
                self.conv(&st, &argt, None);
                self.w(&format!("call ${imp}"));
                self.set_local(*dst);
            }
        }
        Ok(())
    }

    fn set_local(&mut self, v: V) {
        let l = self.local_of[&v];
        self.w(&format!("local.set {l}"));
    }

    fn gen_checked_bin(
        &mut self,
        dst_val: V,
        dst_ovf: V,
        op: IrBin,
        ty: &IrType,
        a: V,
        b: V,
    ) -> Result<(), CodegenError> {
        let sg = is_signed(ty);
        let at = self.ty_of(a);
        let bt = self.ty_of(b);
        let p = wty(ty);
        let bits = ty.bits();

        if op == IrBin::Mul && bits == 64 {
            return Err(CodegenError(
                "checked multiplication of 64-bit integers is not supported by the wasm backend yet".into(),
            ));
        }

        match op {
            IrBin::Add | IrBin::Sub => {
                self.push_val(a);
                self.conv(&at, ty, None);
                self.push_val(b);
                self.conv(&bt, ty, None);
                let base_op = if op == IrBin::Add { "add" } else { "sub" };
                self.w(&format!("{p}.{base_op}"));
                // 桁落ち検出のための準備: r を保存しておく
                let rv = self.local_of[&dst_val];
                self.w(&format!("local.set {rv}"));
                // ovf 計算（オペランドは必ず変換済みの値を積み直す。
                // ローカルには Const::Int 等の生表現が入っているため直接読むと幅が合わない）
                //   符号付き add: ((a^r)&(b^r))<0 / sub: ((a^b)&(a^r))<0
                //   符号なし add: r<a / sub: a<b （ともに unsigned比較）
                if sg {
                    let push_coerced = |g: &mut Self, v: V| {
                        let lt = g.ty_of(v);
                        g.push_val(v);
                        g.conv(&lt, ty, None);
                    };
                    // a ^ (b | r 側)
                    push_coerced(self, a);
                    if op == IrBin::Add {
                        self.w(&format!("local.get {rv}"));
                    } else {
                        push_coerced(self, b);
                    }
                    self.w(&format!("{p}.xor"));
                    if op == IrBin::Add {
                        push_coerced(self, b);
                        self.w(&format!("local.get {rv}"));
                    } else {
                        push_coerced(self, a);
                        self.w(&format!("local.get {rv}"));
                    }
                    self.w(&format!("{p}.xor"));
                    self.w(&format!("{p}.and"));
                    self.w(&format!("{p}.const 0"));
                    self.w(&format!("{p}.lt_s"));
                } else if op == IrBin::Add {
                    self.w(&format!("local.get {rv}"));
                    let lt = self.ty_of(a);
                    self.push_val(a);
                    self.conv(&lt, ty, None);
                    self.w(&format!("{p}.lt_u"));
                } else {
                    let lta = self.ty_of(a);
                    self.push_val(a);
                    self.conv(&lta, ty, None);
                    let ltb = self.ty_of(b);
                    self.push_val(b);
                    self.conv(&ltb, ty, None);
                    self.w(&format!("{p}.lt_u"));
                }
                self.set_local(dst_ovf);
            }
            IrBin::Mul => {
                // 32bit のみ: i64 へ拡張して乗算し、上位ビットで桁落ち判定
                let wide = IrType::I64;
                self.push_val(a);
                self.conv(&at, &wide, Some(sg));
                self.push_val(b);
                self.conv(&bt, &wide, Some(sg));
                self.w("i64.mul");
                let tl = self.wide_local;
                self.w(&format!("local.set {tl}"));
                // fits = (t << 32 >>s 32) == t
                self.w(&format!("local.get {tl}"));
                self.w("i64.const 32");
                self.w("i64.shl");
                self.w("i64.const 32");
                if sg {
                    self.w("i64.shr_s");
                } else {
                    self.w("i64.shr_u");
                }
                self.w(&format!("local.get {tl}"));
                self.w("i64.ne");
                self.set_local(dst_ovf);
                // 結果を 32bit へ切り詰め
                self.w(&format!("local.get {tl}"));
                self.w("i32.wrap_i64");
                self.set_local(dst_val);
            }
            _ => unreachable!(),
        }
        Ok(())
    }

    fn gen_call(
        &mut self,
        dst: Option<&V>,
        func: &str,
        args: &[V],
        ret: &IrType,
    ) -> Result<(), CodegenError> {
        match self.resolve_callee(func)? {
            Callee::Local(idx) => {
                let sret = ret.is_aggregate();
                let mut buf_addr: Option<usize> = None;
                if sret {
                    let sz = self.prog.size_of(ret);
                    self.emit_bump(sz);
                    let l = self.scratch;
                    self.w(&format!("local.set {l}"));
                    buf_addr = Some(l);
                }
                if sret {
                    self.w(&format!("local.get {}", buf_addr.unwrap()));
                }
                let ptys = Self::callee_param_tys(self.prog, idx);
                for (i, a) in args.iter().enumerate() {
                    match ptys.get(i) {
                        Some(pt) => {
                            let lt = self.ty_of(*a);
                            self.push_val(*a);
                            self.conv(&lt, pt, None);
                        }
                        None => self.coerce_arg(*a, "i32"),
                    }
                }
                let sym = sanitize_name(&self.prog.funcs[idx].name);
                self.w(&format!("call ${sym}"));
                if let Some(d) = dst {
                    if sret {
                        self.w(&format!("local.get {}", buf_addr.unwrap()));
                    }
                    self.set_local(*d);
                } else if !sret && !matches!(ret, IrType::Void) {
                    // 破棄される戻り値はスタックから落とす
                    self.w("drop");
                }
            }
            Callee::Import(sig) => {
                for (i, a) in args.iter().enumerate() {
                    let want = sig.params.get(i).copied().unwrap_or("i32");
                    self.coerce_arg(*a, want);
                }
                let sym = sanitize_import_sym(&sig.import_name);
                self.w(&format!("call ${sym}"));
                if let Some(d) = dst {
                    self.set_local(*d);
                } else if !sig.ret.is_empty() {
                    self.w("drop");
                }
            }
        }
        Ok(())
    }

    /// Cast 命令の意味論を反映した変換（値はスタック上）
    fn gen_cast(&mut self, kind: CastKind, from: &IrType, to: &IrType) -> Result<(), CodegenError> {
        match kind {
            CastKind::Trunc => {
                // 64bit スロットならまず wrap
                if wty(from) == "i64" && wty(to) == "i32" {
                    self.w("i32.wrap_i64");
                }
                // 目標幅 < 32bit なら正規化（符号なし: マスク / 符号あり: シフトで符号拡張）
                let b = to.bits();
                if b < 32 {
                    let sh = 32 - b;
                    if is_signed(to) {
                        self.w(&format!("i32.const {sh}"));
                        self.w("i32.shl");
                        self.w(&format!("i32.const {sh}"));
                        self.w("i32.shr_s");
                    } else {
                        let mask = (1u64 << b) - 1;
                        self.w(&format!("i32.const {mask}"));
                        self.w("i32.and");
                    }
                }
            }
            CastKind::Zext | CastKind::Sext => {
                let sg = kind == CastKind::Sext;
                self.conv(from, to, Some(sg));
            }
            CastKind::Sitofp => self.conv(from, to, Some(true)),
            CastKind::Fptosi => self.conv(from, to, Some(true)),
            CastKind::Fptoui => self.conv(from, to, Some(false)),
            CastKind::Fpext | CastKind::Fptrunc => self.conv(from, to, None),
            CastKind::Inttoptr | CastKind::Ptrtoint | CastKind::BoolToInt => self.conv(from, to, None),
            CastKind::IntToBool => {
                // x != 0 を 0/1 へ正規化
                let p = wty(from);
                self.w(&format!("{p}.eqz"));
                self.w("i32.eqz");
                let _ = p;
            }
        }
        Ok(())
    }
}

