struct DataSeg {
    bytes: Vec<u8>,
    /// リテラルid → セルオフセット ({data:u64 @0, len:u64 @8}、ネイティブ版と同一)
    cells: Vec<u64>,
}

fn build_data(prog: &IrProgram) -> DataSeg {
    let mut bytes: Vec<u8> = vec![];
    while bytes.len() % 16 != 0 {
        bytes.push(0);
    }
    let mut cells = Vec::with_capacity(prog.strings.len());
    for g in &prog.strings {
        while bytes.len() % 8 != 0 {
            bytes.push(0);
        }
        let data_off = bytes.len() as u64;
        bytes.extend_from_slice(g.content.as_bytes());
        // セル本体 — ネイティブ版と同じ {data: u64, len: u64} レイアウト。
        // lowering は addr_off(+0/+8) で data/len を読むため 16 バイト幅を維持する。
        // （ポインタ値自体は wasm の 32bit 範囲に収まるため u64 にゼロ拡張で格納）
        while bytes.len() % 8 != 0 {
            bytes.push(0);
        }
        let cell_off = bytes.len() as u64;
        bytes.extend_from_slice(&data_off.to_le_bytes());
        bytes.extend_from_slice(&(g.content.len() as u64).to_le_bytes());
        cells.push(cell_off);
    }
    DataSeg { bytes, cells }
}

