fn ts_type(t: &IrType) -> Option<&'static str> {
    match t {
        IrType::Bool => Some("boolean"),
        IrType::Str => Some("string"),
        IrType::I8 | IrType::I16 | IrType::I32 | IrType::U8 | IrType::U16 | IrType::U32 => Some("number"),
        IrType::I64 | IrType::U64 | IrType::Usize | IrType::Isize => Some("number /* 64-bit */"),
        IrType::F32 | IrType::F64 => Some("number"),
        _ => None,
    }
}

/// C エクスポートから TypeScript 宣言 (.d.ts) を生成する。
pub fn generate_dts(prog: &IrProgram) -> String {
    let mut out = String::new();
    writeln!(out, "// generated by nagiscript (NGS-IR exports -> TypeScript)").ok();
    writeln!(
        out,
        "// Strings cross the boundary as {{ ptr: number, len: number }} views into the exported `memory`."
    )
    .ok();
    writeln!(out).ok();
    for (name, params, ret) in &prog.exports {
        let ps: Vec<String> = params
            .iter()
            .enumerate()
            .map(|(i, (pn, pt))| {
                let pn = if pn.is_empty() { format!("arg{i}") } else { pn.to_string() };
                match ts_type(pt) {
                    Some(t) => format!("{pn}: {t}"),
                    None => format!("/* unsupported type `{}` */ {pn}: never", pt_display(pt)),
                }
            })
            .collect();
        let rt = match ts_type(ret) {
            Some(t) => t.to_string(),
            None => {
                writeln!(
                    out,
                    "// NOTE: `{name}` returns an aggregate/pointer type and cannot be represented in TS."
                )
                .ok();
                "void".to_string()
            }
        };
        writeln!(out, "export function {}({}): {};", name, ps.join(", "), rt).ok();
    }
    out
}

fn pt_display(t: &IrType) -> String {
    match t {
        IrType::Ptr(_) => "*T".to_string(),
        IrType::Array(_, n) => format!("[T; {n}]"),
        IrType::Struct(_) => "struct".to_string(),
        IrType::Enum(_) => "enum".to_string(),
        other => format!("{other:?}"),
    }
}

