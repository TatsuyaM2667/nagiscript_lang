//! NGS-IR → WebAssembly (WAT テキスト) コード生成 + TypeScript 型定義 (.d.ts) 生成。
//!
//! 設計方針:
//! - 依存クレートなしの WAT テキスト出力。wat2wasm 等で .wasm 化する。
//! - 制御フローは「pc ガードチェーン」方式で任意の CFG を機械的に変換する。
//!   すべての仮想レジスタを wasm ローカルに格下げし、各基本ブロックを
//!   `$pc == ブロック番号` のガード付き if 内に配置する。ブロック終端で
//!   `$pc` を更新してからガードチェーンを抜け、ループ先頭へ戻る。
//! - 集約型（struct/enum/array）を返す関数は LLVM 版と同じ sret 規約
//!   （隠し先頭 i32 引数 = 呼び出し側バッファ、memory.copy で実体を転送）。
//! - メモリ: 先頭に文字列データ + {data:u64,len:u64} セル、以降はグローバル
//!   $heap からのバンプアロケータ。関数脱出時に $heap を復元する
//!   （ループ内の alloca は反復間で再利用されない簡易実装）。
//! - ランタイム (__ngs_* / fmod) は "env" imports として要求し、ホスト(JS 等)が
//!   エクスポートされた memory を介して実装する。List/Rc は生ポインタを
//!   ホストと共有する必要があるため本サブセットでは未対応（明示的エラー）。

use std::collections::{HashMap, HashSet};
use std::fmt::Write as _;

use ngs_ir::{CastKind, Const, Inst, IrBin, IrPred, IrProgram, IrType, Term, V};

#[derive(Debug)]
pub struct CodegenError(pub String);

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl std::error::Error for CodegenError {}

