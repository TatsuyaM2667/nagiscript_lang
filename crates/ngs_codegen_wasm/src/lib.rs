    #[test]
    fn wat2wasm_accepts_output_when_available() {
        let prog = full_feature_program();
        let wat = generate_wat(&prog).expect("generate_wat");
        let dir = std::env::temp_dir().join("ngs_wat_test");
        std::fs::create_dir_all(&dir).ok();
        let wat_path = dir.join("test.wat");
        std::fs::write(&wat_path, &wat).expect("write wat");

        if std::process::Command::new("wat2wasm").arg("--version").output().is_err() {
            // ツールが無い環境ではスキップ
            return;
        }
        let wasm_path = dir.join("test.wasm");
        let out = std::process::Command::new("wat2wasm")
            .args([wat_path.to_str().unwrap(), "-o", wasm_path.to_str().unwrap()])
            .output()
            .expect("run wat2wasm");
        assert!(
            out.status.success(),
            "wat2wasm failed:\n{}\n--- WAT ---\n{wat}",
            String::from_utf8_lossy(&out.stderr)
        );
    }

    /// 分岐・ループ・構造体(sret)・文字列・checked bin・cast を網羅する手組みプログラム
    fn full_feature_program() -> IrProgram {
        // struct Point { x:i32, y:i32 }  (sid 0)
        // fn area(p: Point) -> i32 { p.x * p.y }        ← checked mul (i32)
        // fn make() -> Point { Point{x:3,y:7} }         ← sret
        // fn main() { let p = make(); let a = area(p); print(if a > 10 {"big"} else {"small"}) }
        let structs = vec![ngs_ir::IrStruct {
            mangled: "Point".into(),
            fields: vec![("x".into(), IrType::I32), ("y".into(), IrType::I32)],
            is_list: false,
        }];

        // area(p: ptr(Point)) -> i32
        let mut area =
            FnBuilder::new("_NGS_area".into(), vec![("p".into(), IrType::Struct(0))], IrType::I32, true);
        let px = area.field_addr(0, 0, 0);
        let xv = area.load(px, IrType::I32);
        let py = area.field_addr(0, 0, 1);
        let yv = area.load(py, IrType::I32);
        let (_pv, ovf) = area.checked_bin(IrBin::Mul, IrType::I32, xv, yv);
        let _big = area.str_lit("big");
        let _small = area.str_lit("small");
        let zero = area.const_int(0);
        let ok = area.cmp(IrPred::Eq, IrType::Bool, ovf, zero);
        let (then_b, tb) = area.new_block("then");
        let (else_b, _eb) = area.new_block("else");
        let (cont_b, cb) = area.new_block("cont");
        area.cond_br(ok, &tb, &_eb.to_string());
        area.position(then_b);
        area.br(&cb);
        area.position(else_b);
        area.unreachable(); // オーバーフロー時は abort（簡略化）
        area.position(cont_b);
        area.ret(Some(xv));

        // make() -> Point (sret)
        let mut make = FnBuilder::new("_NGS_make".into(), vec![], IrType::Struct(0), true);
        let buf = make.alloca(IrType::Struct(0));
        let three = make.const_int(3);
        let seven = make.const_int(7);
        let fx = make.field_addr(buf, 0, 0);
        let fy = make.field_addr(buf, 0, 1);
        make.store(fx, three, IrType::I32);
        make.store(fy, seven, IrType::I32);
        make.ret(Some(buf));

        // main
        let mut main = FnBuilder::new("__NGS_main".into(), vec![], IrType::Void, false);
        let p = main.call("_NGS_make", vec![], IrType::Struct(0)).unwrap();
        let a = main.call("_NGS_area", vec![p], IrType::I32).unwrap();
        let ten = main.const_int(10);
        let gt = main.cmp(IrPred::Gt, IrType::I32, a, ten);
        let (bb, blab) = main.new_block("b1");
        let (eb, elab) = main.new_block("b2");
        let (jb, jlab) = main.new_block("join");
        main.cond_br(gt, &blab, &elab);
        main.position(bb);
        main.br(&jlab);
        main.position(eb);
        main.br(&jlab);
        main.position(jb);
        let msg = main.str_lit("done");
        let dp = main.addr_off(msg, 0);
        let lp = main.addr_off(msg, 8);
        let d = main.load(dp, IrType::Ptr(std::rc::Rc::new(IrType::U8)));
        let l = main.load(lp, IrType::Usize);
        main.call("__ngs_println_str", vec![d, l], IrType::Void);
        main.ret(None);

        let mut prog = IrProgram {
            structs,
            strings: vec![],
            main_name: Some("__NGS_main".into()),
            exports: vec![],
            enums: vec![],
            funcs: vec![],
        };
        // Const::Str(id) はグローバルプールのインデックスなので各ビルダに開始位置を教える
        let mut pool: Vec<String> = vec![];
        for mut fb in [area, make, main] {
            fb.set_strings_base(pool.len() as u32);
            pool.append(&mut fb.strings);
            prog.funcs.push(fb.func);
        }
        prog.strings = pool.into_iter().map(|s| ngs_ir::GlobalString { content: s }).collect();
        prog
    }
