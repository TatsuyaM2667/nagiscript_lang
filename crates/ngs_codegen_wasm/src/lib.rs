/// 本サブセットで未対応のランタイム関数
const UNSUPPORTED: &[&str] = &[
    "__ngs_list_new",
    "__ngs_list_push",
    "__ngs_list_len",
    "__ngs_list_at",
    "__ngs_list_free",
    "__ngs_rc_new",
    "__ngs_rc_inc",
    "__ngs_rc_dec",
];

struct ImportSig {
    import_name: String,
    params: Vec<&'static str>,
    ret: &'static str,
}

fn resolve_import(name: &str) -> Option<ImportSig> {
    // lowering は float の剰余を __ngs_fmod 呼び出しとして出力する
    let key = if name == "fmod" { "__ngs_fmod" } else { name };
    if UNSUPPORTED.contains(&key) {
        return None;
    }
    IMPORTS
        .iter()
        .find(|(n, _, _)| *n == key)
        .map(|(n, ps, r)| ImportSig { import_name: n.to_string(), params: ps.to_vec(), ret: r })
}

